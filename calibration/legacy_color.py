def match_rgb(red: int, green: int, blue: int) -> tuple[int, int, int]:
    """Map a display RGB target to a calibrated QR65 command."""
    channels = (red, green, blue)
    if any(type(value) is not int or not 0 <= value <= 255 for value in channels):
        raise ValueError("RGB channels must be integers between 0 and 255")

    peak = max(channels)
    if peak == 0:
        return 0, 0, 0
    saturation = (peak - min(channels)) / peak
    if saturation == 0:
        return channels

    normalized = tuple(channel / 255 for channel in channels)
    correction = [0.0, 0.0, 0.0]
    for center, coefficients in zip(
        PROFILE_CENTERS, PROFILE_COEFFICIENTS, strict=True
    ):
        distance = sum(
            (channel - center_channel / 255) ** 2
            for channel, center_channel in zip(normalized, center, strict=True)
        )
        weight = exp(-PROFILE_GAMMA * distance)
        for index, coefficient in enumerate(coefficients):
            correction[index] += weight * coefficient

    return tuple(
        round(255 * min(1.0, max(0.0, channel + saturation * adjustment)))
        for channel, adjustment in zip(normalized, correction, strict=True)
    )
